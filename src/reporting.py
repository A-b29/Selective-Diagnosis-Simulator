"""
reporting.py - Report exporter for Selective Diagnosis Simulator.
"""

from pathlib import Path
from typing import Dict, Any, List
import json


def export_selective_results_json(data: Dict[str, Any], output_path: Path) -> Path:
    """Save evaluation metrics and calibration results to JSON."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, default=str)
    return output_path


def generate_selective_markdown(
    baseline_metrics: Dict[str, float],
    calibration_info: Dict[str, Any],
    selective_metrics: Dict[str, Any],
    output_path: Path
) -> Path:
    """Generate Markdown report for selective prediction and abstention."""
    output_path.parent.mkdir(parents=True, exist_ok=True)

    lines = [
        "# Selective Diagnosis & Abstention Simulation Report",
        "",
        "> **Non-Clinical Research Notice:** This prototype evaluates mathematical trade-offs between "
        "coverage and error rate via abstention. It is **not** an authorized clinical triage or diagnostic tool.",
        "",
        "## 1. Baseline Performance (100% Coverage)",
        f"- **Test Accuracy:** `{baseline_metrics.get('accuracy', 0.0):.2%}`",
        f"- **Baseline Error Rate:** `{baseline_metrics.get('error_rate', 0.0):.2%}`",
        f"- **Weighted F1 Score:** `{baseline_metrics.get('f1_weighted', 0.0):.4f}`",
        f"- **AUROC:** `{baseline_metrics.get('auroc', 0.0):.4f}`",
        "",
        "## 2. Calibration Analysis",
        f"- **Learned Temperature (T):** `{calibration_info.get('temperature', 1.0):.3f}`",
        f"- **Uncalibrated ECE:** `{calibration_info.get('uncalibrated_ece', 0.0):.4f}`",
        f"- **Calibrated ECE:** `{calibration_info.get('calibrated_ece', 0.0):.4f}`",
        f"- **Brier Score (Calibrated):** `{calibration_info.get('calibrated_brier', 0.0):.4f}`",
        "",
        "## 3. Selective Prediction Under Risk Budget",
        f"- **Target Risk Budget:** `<= {selective_metrics.get('target_risk_budget', 0.0):.1%}`",
        f"- **Selected Confidence Threshold (θ*):** `{selective_metrics.get('optimal_threshold', 0.0):.3f}` *(selected on Validation set)*",
        f"- **Held-Out Test Coverage:** `{selective_metrics.get('test_coverage', 0.0):.2%}` "
        f"({selective_metrics.get('accepted_count', 0)} accepted, {selective_metrics.get('abstained_count', 0)} referred to specialist)",
        f"- **Held-Out Test Selective Risk:** `{selective_metrics.get('test_selective_risk', 0.0):.2%}` "
        f"(Errors in accepted cohort: {selective_metrics.get('accepted_errors', 0)})",
        "",
        "## 4. Key Takeaways",
        "- By abstaining on low-confidence cases, the error rate among accepted patients drops significantly.",
        "- Choosing the decision threshold strictly on the validation set guarantees realistic, non-overfitted test estimates.",
        "",
        "---",
        "*Generated by Selective Diagnosis Simulator.*"
    ]

    content = "\n".join(lines)
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(content)
    return output_path
